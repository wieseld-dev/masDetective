#!/usr/bin/env python3
"""
build_robust_visible_generator_rows_v1.py

Relabel ONE on-policy curriculum cycle with a deployable pre-execution objective:

    visible_MI_K(q, belief)

No actual candidate output, selected_roles, truth_roles, or true K is used to
score a candidate.

Why stage_10/cycle_02?
Its candidates were generated by stage_10_cycle_01/policy, so old_logp is
on-policy for the exact adapter from which we branch. This keeps the PPO-style
update coherent.

Robust objective:
  top quartile      +1.25
  upper-middle      +0.75
  lower-middle      -0.25
  bottom quartile   -1.75

This is centered (mean ~0 for groups of 8) but deliberately punishes the lower
tail much harder than ordinary group-relative training. The goal is not merely
"one excellent probe in the pool"; it is to lift the floor of the whole
generator distribution.
"""

from __future__ import annotations
import argparse, json, sys
from collections import defaultdict
from pathlib import Path
import numpy as np
import torch

sys.path.insert(0, str(Path("analysis").resolve()))
import observation_model_v1 as om
import visible_adaptive_bridge_v1 as vb


def read_jsonl(p):
    out=[]
    with Path(p).open(encoding="utf-8") as f:
        for line in f:
            line=line.strip()
            if line: out.append(json.loads(line))
    return out


def write_jsonl(p, rows):
    p=Path(p); p.parent.mkdir(parents=True,exist_ok=True)
    with p.open("w",encoding="utf-8") as f:
        for x in rows: f.write(json.dumps(x,ensure_ascii=False)+"\n")


def robust_rank_advantages(scores):
    n=len(scores)
    order=np.argsort(np.asarray(scores,float))
    adv=np.zeros(n,dtype=np.float64)
    # rank-based CVaR-ish shaping; strongest pressure on bottom quartile.
    for rank,j in enumerate(order):
        frac=(rank+0.5)/n
        if frac <= .25: a=-1.75
        elif frac <= .50: a=-.25
        elif frac <= .75: a=.75
        else: a=1.25
        adv[j]=a
    # exact centering protects update scale for non-8 candidate groups.
    adv -= adv.mean()
    return adv


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--root",default="artifacts/adaptive_v11_curriculum_v2")
    ap.add_argument("--cycle",default="artifacts/adaptive_v11_curriculum_v2/stage_10/cycle_02")
    ap.add_argument("--obs-dir",default="artifacts/observation_model_v1")
    ap.add_argument("--vis-dir",default="artifacts/visible_output_fingerprint_v1")
    ap.add_argument("--cal-dir",default="artifacts/calibrated_bayes_diag_v1")
    ap.add_argument("--out-root",default="artifacts/robust_visible_generator_v1/train_rows")
    ap.add_argument("--particles-per-k",type=int,default=8)
    ap.add_argument("--batch-size",type=int,default=4096)
    ap.add_argument("--seed",type=int,default=91)
    a=ap.parse_args()

    root=Path(a.root); cycle=Path(a.cycle); obsdir=Path(a.obs_dir)
    visdir=Path(a.vis_dir); caldir=Path(a.cal_dir); out=Path(a.out_root)
    out.mkdir(parents=True,exist_ok=True)

    examples,roles,_,_=om.collect_examples(root)
    split=json.loads((obsdir/"split_systems.json").read_text())
    train_systems=set(map(str,split["train"]))
    val_systems=set(map(str,split["val"]))

    # Exact target cycle only.
    cyc_abs=str(cycle.resolve())
    idx=[]
    for i,x in enumerate(examples):
        try: parent_abs=str(Path(x["parent"]).resolve())
        except Exception: parent_abs=str(x["parent"])
        if parent_abs==cyc_abs and str(x["system_id"]) in train_systems:
            idx.append(i)
    if not idx:
        raise RuntimeError(f"No TRAIN-split examples found for {cycle}")

    Q=np.load(obsdir/"query_embeddings.npy").astype(np.float32)
    O=np.load(visdir/"output_embeddings.npy").astype(np.float32)
    X=np.concatenate([Q,O],axis=1)
    tri=np.array([i for i,x in enumerate(examples) if str(x["system_id"]) in train_systems],int)
    vai=np.array([i for i,x in enumerate(examples) if str(x["system_id"]) in val_systems],int)
    Y=vb.labels(examples,roles,"selected_roles")

    print("[1/5] fitting frozen visible fingerprint channel...",flush=True)
    fp_models,fp_cals,thr,tpr,fpr,_=vb.fit_visible_detector(X,Y,tri,vai)

    print("[2/5] loading calibrated forward observation model...",flush=True)
    ckpt=torch.load(obsdir/"model.pt",map_location="cpu")
    model=om.ObservationNet(
        qdim=ckpt["query_embedding_dim"], n_roles=len(roles),
        hidden=ckpt["hidden"], dropout=ckpt["dropout"]
    )
    model.load_state_dict(ckpt["state_dict"]); model.eval()

    ri={r:i for i,r in enumerate(roles)}
    pos=np.zeros(len(roles),float)
    for i in tri:
        for r in examples[i]["selected_roles"]: pos[ri[r]]+=1
    posw=np.clip((len(tri)-pos)/np.maximum(pos,1.0),1.0,20.0)
    log_posw=np.log(posw)

    cs=json.loads((caldir/"summary.json").read_text())
    T=float(cs["true_Z_probability_calibration"]["corrected_plus_temperature"]["best_T"])

    print("[3/5] indexing exact historical prompt/completion/logprobs...",flush=True)
    raw={}
    for rnd in range(1,100):
        found=False
        for name in [
            f"responses_train_round_{rnd:02d}.jsonl",
            f"score_input_train_round_{rnd:02d}.jsonl",
            f"candidate_pool_train_round_{rnd:02d}.jsonl",
            f"candidates_train_round_{rnd:02d}.jsonl",
        ]:
            p=cycle/name
            if not p.exists(): continue
            found=True
            for z in read_jsonl(p):
                sid=str(z.get("session_id") or z.get("system_id") or "")
                ci=int(z.get("candidate_index",0))
                key=(sid,rnd,ci)
                old=raw.get(key,{})
                # Prefer records with prompt/completion and both logprobs.
                score=sum(k in z and z.get(k) not in (None,"") for k in ["prompt","completion","old_logp","ref_logp"])
                oldscore=sum(k in old and old.get(k) not in (None,"") for k in ["prompt","completion","old_logp","ref_logp"])
                if score>=oldscore: raw[key]=z
        if not found and rnd>20: break

    groups=defaultdict(list)
    for i in idx:
        x=examples[i]
        groups[(str(x["system_id"]),int(x["round"]))].append((i,x))

    print(f"[4/5] computing visible-MI labels for {len(groups)} states / {len(idx)} candidates...",flush=True)
    rows=[]; group_report=[]
    max_round=max(int(x["round"]) for x in examples)
    for gi,((sid,rnd),items) in enumerate(sorted(groups.items())):
        items=sorted(items,key=lambda ix:int(ix[1]["candidate_index"]))
        if len(items)<2: continue
        x0=items[0][1]
        belief=np.array([x0["role_probs"][r] for r in roles],dtype=np.float32)
        # Observation model was trained with these four explicit K features.
        kvec=np.array([x0["k_probs"].get(str(k),0.0) for k in [3,4,5,6]],dtype=np.float32)
        rnorm=float(rnd/max(max_round,1))
        rng=np.random.default_rng(abs(hash((sid,rnd,a.seed)))%(2**32))
        Z,W,Klabels,Kprior=vb.stratified_particles(
            x0["k_probs"],x0["role_probs"],roles,a.particles_per_k,rng
        )
        qg=np.stack([Q[i] for i,_ in items]).astype(np.float32)
        L=vb.particle_logits(model,qg,belief,kvec,rnorm,Z,"cpu",a.batch_size)
        pY=vb.calibrated_hidden_probs(L,log_posw,T)
        pE=vb.detector_channel_probs(pY,tpr,fpr)
        scores=vb.mi_k(pE,W,Klabels,Kprior)
        adv=robust_rank_advantages(scores)

        used=0
        for j,(i,x) in enumerate(items):
            ci=int(x["candidate_index"])
            z=raw.get((sid,rnd,ci))
            if z is None: continue
            prompt=str(z.get("prompt") or "")
            completion=str(z.get("completion") or z.get("raw_completion") or "")
            if not prompt or not completion: continue
            if z.get("old_logp") is None or z.get("ref_logp") is None: continue
            rows.append({
                "session_id":sid,
                "round":int(rnd),
                "candidate_index":ci,
                "group_id":f"{sid}::orig_r{rnd:02d}",
                "prompt":prompt,
                "completion":completion,
                "old_logp":float(z["old_logp"]),
                "ref_logp":float(z["ref_logp"]),
                "reward":float(scores[j]),
                "local_advantage":float(adv[j]),
                "chosen_for_continuation":False,
                "reward_breakdown_training_only":{
                    "objective":"predicted_visible_mi_k_pre_execution",
                    "visible_mi_k":float(scores[j]),
                    "robust_rank_advantage":float(adv[j]),
                    "uses_actual_output":False,
                    "uses_true_k":False,
                    "uses_selected_roles":False,
                },
            })
            used+=1
        group_report.append({
            "session_id":sid,"round":rnd,"candidates":used,
            "mi_mean":float(np.mean(scores)),
            "mi_min":float(np.min(scores)),
            "mi_p25":float(np.quantile(scores,.25)),
            "mi_median":float(np.median(scores)),
            "mi_max":float(np.max(scores)),
        })
        if (gi+1)%100==0: print(f"  scored {gi+1}/{len(groups)} states",flush=True)

    if len(rows)<100:
        raise RuntimeError(f"Too few usable rows: {len(rows)}")

    # One synthetic horizon file so the existing updater can consume it.
    write_jsonl(out/"train_rows_round_01.jsonl",rows)
    summary={
        "source_cycle":str(cycle),
        "source_policy_that_generated_rows":"artifacts/adaptive_v11_curriculum_v2/checkpoints/stage_10_cycle_01/policy",
        "systems_split":"observation_model_v1 TRAIN systems only",
        "rows":len(rows),
        "groups":len(group_report),
        "particles_per_K":a.particles_per_k,
        "candidate_score":"expected visible fingerprint mutual information about K",
        "actual_output_used_for_reward":False,
        "true_K_used_for_reward":False,
        "selected_roles_used_for_reward":False,
        "robust_advantages":{
            "bottom_quartile":-1.75,
            "lower_middle":-0.25,
            "upper_middle":0.75,
            "top_quartile":1.25,
            "per_group_centered":True,
        },
        "mi_distribution":{
            "mean":float(np.mean([r["reward"] for r in rows])),
            "p10":float(np.quantile([r["reward"] for r in rows],.10)),
            "p25":float(np.quantile([r["reward"] for r in rows],.25)),
            "median":float(np.median([r["reward"] for r in rows])),
            "p75":float(np.quantile([r["reward"] for r in rows],.75)),
        }
    }
    (out/"build_summary.json").write_text(json.dumps(summary,indent=2),encoding="utf-8")
    print("[5/5] saved",out/"train_rows_round_01.jsonl",flush=True)
    print(json.dumps(summary,indent=2),flush=True)


if __name__=="__main__":
    main()
