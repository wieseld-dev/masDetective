#!/bin/bash
set -euo pipefail
cd "$HOME/mas_rl_detective"

ROOT="artifacts/adaptive_v11_curriculum_v2"
OUT="artifacts/robust_visible_generator_v1"
BRANCH="$ROOT/checkpoints/stage_10_cycle_01/policy"
ROBUST="$OUT/policy"

[[ -d "$BRANCH" ]] || { echo "Missing branch policy: $BRANCH" >&2; exit 2; }
[[ -f "cluster/curriculum_update_4090.sbatch" ]] || { echo "Missing existing curriculum updater sbatch" >&2; exit 2; }

HASH="$ROOT/v11_source_sha256.txt"
RET="$ROOT/v11_retention.jsonl"
[[ -s "$HASH" ]] || { echo "Missing $HASH" >&2; exit 2; }
[[ -s "$RET" ]] || { echo "Missing $RET" >&2; exit 2; }

mkdir -p "$OUT" logs

L=$(sbatch --parsable robust_visible_generator_labels_v1.sbatch)
echo "LABEL_JOB=$L"

# Exact on-policy branch:
# stage10/cycle02 samples were generated by stage10_cycle01/policy.
U=$(sbatch --parsable \
  --dependency="afterok:$L" \
  --export="ALL,CURR_ROOT=$OUT/train_rows,CURR_HORIZON=1,CURR_INPUT_ADAPTER=$BRANCH,CURR_OUTPUT_ADAPTER=$ROBUST,CURR_V11=artifacts/v11_policy,CURR_V11_HASH_FILE=$HASH,CURR_RETENTION=$RET,CURR_LR=2e-6,CURR_KL_BETA=0.02,CURR_RETENTION_WEIGHT=0.08,CURR_MC_WEIGHT=0.0,CURR_EPOCHS=1,CURR_GRAD_ACCUM=8" \
  cluster/curriculum_update_4090.sbatch)
echo "TRAIN_JOB=$U"

E=$(sbatch --parsable --dependency="afterok:$U" robust_visible_generator_eval_v1.sbatch)
echo "EVAL_JOB=$E"

printf "labels\t%s\ntrain\t%s\neval\t%s\n" "$L" "$U" "$E" | tee "$OUT/jobs.tsv"
echo "$E" > "$OUT/final_job.txt"

echo
echo "ROBUST VISIBLE GENERATOR V1 SUBMITTED"
echo "Track: squeue -j $L,$U,$E"
echo "Final: cat $OUT/eval/summary.json"
